// ИНИЦИАЛИЗАЦИЯ ОПРОСА ПРИ ЗАГРУЗКЕ СТРАНИЦЫ
// ============================================
document.addEventListener('DOMContentLoaded', function() {
    const quizContainer = document.getElementById('quiz-content');
    if (!quizContainer) return; // Если мы не на странице урока, выходим

    // 1. Определяем класс из имени файла или URL
    const path = window.location.pathname;
    let grade = 6; // По умолчанию
    if (path.includes('grade7')) grade = 7;
    if (path.includes('grade8')) grade = 8;

    // 2. УМНОЕ определение номера урока
    const urlParams = new URLSearchParams(window.location.search);
    let lesson = urlParams.get('lesson');
    
    if (!lesson) {
        // Пытаемся извлечь цифру из имени файла
        // Например, из "lesson2-grade7.html" извлечет "2"
        const match = path.match(/lesson(\d+)-grade\d+\.html/);
        if (match) {
            lesson = match[1];
        } else if (path.includes('lesson-grade')) {
            // Если это просто lesson-grade6.html, то это урок 1
            lesson = 1;
        } else {
            lesson = 1;
        }
    }

    // Загружаем правильный опрос
    loadQuiz(grade, parseInt(lesson));
});